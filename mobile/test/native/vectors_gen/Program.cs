// Generates test/native/crypto_vectors.h from the *Windows* algorithm.
//
// Every primitive here is the same one the Windows client/host use
// (System.Security.Cryptography => BCrypt):
//   * ECDH P-256 raw X coordinate  (P2PCoordinator.DeriveSessionAesKey)
//   * HKDF-SHA256(ikm=shared, salt=token16, info="OSM1-SESSION-KEY-V1")
//   * authTag = HMAC-SHA256(SHA256(UTF8(UPPER(TRIM(code)))),
//                           token || challengeNonce || clientSpki || hostSpki)
//   * directional subkeys = HMAC-SHA256(masterKey, "OSM1-C2H-AES256-GCM" /
//                           "OSM1-H2C-AES256-GCM")        (OsmiumTransport.cpp:958)
//   * AES-256-GCM frame with nonce [prefix4][role][seq7 LE] and AAD = the
//     first 12 header bytes                  (OsmiumTransport EncryptFrame)
//
// Run:  dotnet run -c Release
// It rewrites ../crypto_vectors.h next to this project's parent directory.

using System.Buffers.Binary;
using System.Security.Cryptography;
using System.Text;

const string ClientPkcs8B64 =
    "MIGHAgEAMBMGByqGSM49AgEGCCqGSM49AwEHBG0wawIBAQQgMDb/92qDmJZd+kGG/wqtQbqtm7aedMusumzjDAKStCqhRANCAAQmhqsGWrH2NnSAWffxqGITVWbcAWhm8ZzbXKLIr45l/qjiJxfwjSjlLz3AfZPVZji5o+zsfiFrMlnia3oaA7Yf";
const string HostPkcs8B64 =
    "MIGHAgEAMBMGByqGSM49AgEGCCqGSM49AwEHBG0wawIBAQQgbWpxDx2NOy7I5QFD5fNaZo9hAR27Wd2GTFU39hDbtz2hRANCAASd+76oRaenu28wHfYjto2kDdETQvtl+vA/uMLz26MAfnCV8pgF1Svzld57+APSsPz6jt26F3Owg1k92OtWnike";

using var client = ECDiffieHellman.Create();
client.ImportPkcs8PrivateKey(Convert.FromBase64String(ClientPkcs8B64), out _);
using var host = ECDiffieHellman.Create();
host.ImportPkcs8PrivateKey(Convert.FromBase64String(HostPkcs8B64), out _);

byte[] clientSpki = client.ExportSubjectPublicKeyInfo();
byte[] hostSpki = host.ExportSubjectPublicKeyInfo();
byte[] shared = client.DeriveRawSecretAgreement(host.PublicKey);
byte[] token = Enumerable.Range(0, 16).Select(i => (byte)i).ToArray();
byte[] nonce = Enumerable.Range(0, 32).Select(i => (byte)(0xA0 + i)).ToArray();
const string RawCode = "  ab-12 cd  ";
string normalizedCode = RawCode.Trim().ToUpperInvariant();

byte[] aesKey = HKDF.DeriveKey(
    HashAlgorithmName.SHA256,
    shared,
    32,
    salt: token,
    info: Encoding.ASCII.GetBytes("OSM1-SESSION-KEY-V1"));

byte[] codeHash = SHA256.HashData(Encoding.UTF8.GetBytes(normalizedCode));
using var hmac = new HMACSHA256(codeHash);
byte[] authInput = Concat(token, nonce, clientSpki, hostSpki);
byte[] authTag = hmac.ComputeHash(authInput);

byte[] c2h = HMACSHA256.HashData(aesKey, Encoding.ASCII.GetBytes("OSM1-C2H-AES256-GCM"));
byte[] h2c = HMACSHA256.HashData(aesKey, Encoding.ASCII.GetBytes("OSM1-H2C-AES256-GCM"));

// Client -> host frame: AuthRequestPayload (hdr + 32-byte tag + 6 int32).
byte[] clientPlain = new byte[60];
clientPlain[0] = 0x10; // AppPacketType.AuthRequest
for (int i = 0; i < 32; i++) clientPlain[4 + i] = (byte)(0x40 + i);
BinaryPrimitives.WriteInt32LittleEndian(clientPlain.AsSpan(36), 1920);
BinaryPrimitives.WriteInt32LittleEndian(clientPlain.AsSpan(40), 1080);
BinaryPrimitives.WriteInt32LittleEndian(clientPlain.AsSpan(44), 60);
BinaryPrimitives.WriteInt32LittleEndian(clientPlain.AsSpan(48), 12000);
BinaryPrimitives.WriteInt32LittleEndian(clientPlain.AsSpan(52), 0);
BinaryPrimitives.WriteInt32LittleEndian(clientPlain.AsSpan(56), 0);

byte[] clientFrame = BuildFrame(c2h, seq: 1, role: 1, new byte[] { 0xDE, 0xAD, 0xBE, 0xEF }, clientPlain);

// Host -> client frame with a sequence that exercises the high flags word.
byte[] hostPlain = Encoding.ASCII.GetBytes("{\"type\":\"status\"} ");
byte[] hostFrame = BuildFrame(h2c, seq: 0x0000000100000005, role: 2, new byte[] { 0xCA, 0xFE, 0xBA, 0xBE }, hostPlain);

var sb = new StringBuilder();
sb.AppendLine("// AUTO-GENERATED by test/native/vectors_gen (dotnet run -c Release).");
sb.AppendLine("// Do not edit: the fixture is the Windows/BCrypt output for the same inputs.");
sb.AppendLine("#pragma once");
sb.AppendLine("#include <cstdint>");
sb.AppendLine();
sb.AppendLine("namespace osmium_vectors {");
Append("kClientPkcs8", Convert.FromBase64String(ClientPkcs8B64));
Append("kClientSpki", clientSpki);
Append("kHostPkcs8", Convert.FromBase64String(HostPkcs8B64));
Append("kHostSpki", hostSpki);
Append("kSharedSecret", shared);
Append("kToken", token);
Append("kChallengeNonce", nonce);
Append("kAesKey", aesKey);
Append("kAuthTag", authTag);
Append("kC2hKey", c2h);
Append("kH2cKey", h2c);
Append("kClientPlain", clientPlain);
Append("kClientFrame", clientFrame);
Append("kHostPlain", hostPlain);
Append("kHostFrame", hostFrame);
sb.AppendLine($"inline constexpr const char* kAccessCode = \"{RawCode}\";");
sb.AppendLine($"inline constexpr const char* kNormalizedCode = \"{normalizedCode}\";");
sb.AppendLine("} // namespace osmium_vectors");

string outPath = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../crypto_vectors.h"));
File.WriteAllText(outPath, sb.ToString());
Console.WriteLine($"wrote {outPath}");

void Append(string name, byte[] data)
{
    sb.AppendLine($"inline constexpr uint8_t {name}[] = {{");
    for (int i = 0; i < data.Length; i += 12)
    {
        sb.Append("    ");
        sb.Append(string.Join(", ", data.Skip(i).Take(12).Select(b => $"0x{b:X2}")));
        sb.AppendLine(",");
    }
    sb.AppendLine("};");
    sb.AppendLine($"inline constexpr size_t {name}Len = {data.Length};");
    sb.AppendLine();
}

static byte[] BuildFrame(byte[] key, ulong seq, byte role, byte[] prefix, byte[] plain)
{
    byte[] header = new byte[40];
    Encoding.ASCII.GetBytes("OSM1").CopyTo(header, 0);
    header[4] = 1;    // kVersion
    header[5] = 0x10; // WireMsgType.EncryptedData
    BinaryPrimitives.WriteUInt16LittleEndian(header.AsSpan(6), (ushort)((seq >> 32) & 0xFFFF));
    BinaryPrimitives.WriteUInt32LittleEndian(header.AsSpan(8), (uint)(seq & 0xFFFFFFFF));
    prefix.CopyTo(header, 12);
    header[16] = role;
    for (int i = 0; i < 7; i++) header[17 + i] = (byte)((seq >> (i * 8)) & 0xFF);

    byte[] nonce = header.AsSpan(12, 12).ToArray();
    byte[] aad = header.AsSpan(0, 12).ToArray();
    byte[] cipher = new byte[plain.Length];
    byte[] tag = new byte[16];
    using var gcm = new AesGcm(key, 16);
    gcm.Encrypt(nonce, plain, cipher, tag, aad);
    tag.CopyTo(header, 24);
    return Concat(header, cipher);
}

static byte[] Concat(params byte[][] parts)
{
    byte[] result = new byte[parts.Sum(p => p.Length)];
    int offset = 0;
    foreach (byte[] part in parts)
    {
        part.CopyTo(result, offset);
        offset += part.Length;
    }
    return result;
}
